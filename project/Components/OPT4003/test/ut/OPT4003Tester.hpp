// ======================================================================
// \title  OPT4003Tester.hpp
// \brief  Unit test harness for the OPT4003 component.
//
// Stands in for the I2C bus driver so the component can be exercised with no
// hardware. The fake sensor answers reads from a small register file, can
// hold off the conversion-ready flag for a set number of polls, records the
// register sequence, and can be told to fail specific transactions.
// ======================================================================

#ifndef PROJECT_OPT4003_TESTER_HPP
#define PROJECT_OPT4003_TESTER_HPP

#include "OPT4003GTestBase.hpp"
#include "project/Components/OPT4003/OPT4003.hpp"

namespace project {

class OPT4003Tester final : public OPT4003GTestBase {
  public:
    static constexpr FwSizeType MAX_HISTORY_SIZE = 64;
    static constexpr FwEnumStoreType TEST_INSTANCE_ID = 0;
    static constexpr FwSizeType TEST_INSTANCE_QUEUE_DEPTH = 10;

    OPT4003Tester();
    ~OPT4003Tester() override;

    // ----------------------------------------------------------------------
    // Test cases
    // ----------------------------------------------------------------------

    //! Boot reads DEVICE_ID, then writes the configuration word.
    void testBoot();

    //! A part with the wrong ID is never configured and stays absent.
    void testBootWrongDeviceId();

    //! A bus failure during boot leaves the sensor absent.
    void testBootBusFailure();

    //! A sensor that has not booted never touches the bus.
    void testReadBeforeBoot();

    //! A read polls FLAGS once, then reads both result registers.
    void testRead();

    //! A read keeps polling FLAGS until the conversion is ready.
    void testReadWaitsForConversion();

    //! A read that never sees conversion-ready still returns the result.
    void testReadTimesOut();

    //! A failed result read is reported and publishes nothing.
    void testReadResultFailure();

    //! readFlags decodes the threshold and overload bits.
    void testReadFlags();

    //! configure() moves every transaction to the new address.
    void testConfigureAddress();

    //! The rate-group port boots once, then samples on every tick.
    void testRunBootsThenSamples();

    //! The error event throttles, and a clean read re-arms it.
    void testErrorThrottle();

  private:
    // Definitions are generated by UT_AUTO_HELPERS.
    void connectPorts();
    void initComponents();

    // ----------------------------------------------------------------------
    // Fake bus
    // ----------------------------------------------------------------------

    Drv::I2cStatus from_busWriteRead_handler(FwIndexType portNum,
                                             U32 address,
                                             Fw::Buffer& writeBuffer,
                                             Fw::Buffer& readBuffer) override;
    Drv::I2cStatus from_busWrite_handler(FwIndexType portNum, U32 address, Fw::Buffer& buffer) override;

    //! Register contents the fake sensor reports. FLAGS has the
    //! conversion-ready bit added once enough polls have gone by.
    U16 valueForRegister(U8 reg);

    //! Boot the component against a healthy bus and forget the traffic.
    void bootCleanly();

    //! One recorded bus transaction.
    struct Transaction {
        U32 address;
        U8 reg;
        bool write;
    };

    //! Assert that transaction `index` targeted this address and register.
    void assertTransaction(U32 index, U32 address, U8 reg, bool write) const;

    //! Make every bus transaction fail with this status.
    void failEverything(Drv::I2cStatus status);

    //! Make just this one register fail; everything else succeeds.
    void failOnly(U8 reg, Drv::I2cStatus status);

    //! Let every transaction succeed again.
    void failNothing();

    //! Forget recorded transactions and all port history.
    void resetRecording();

    OPT4003 component;

    // Fake register file.
    U16 m_deviceId;
    U16 m_resultMsb;
    U16 m_resultLsb;
    U16 m_flags;

    //! FLAGS reads that report "not ready" before the bit is set.
    U32 m_pollsUntilReady = 0;
    //! Never set the conversion-ready bit.
    bool m_neverReady = false;

    // Injected-failure configuration.
    Drv::I2cStatus m_forcedStatus = Drv::I2cStatus::I2C_OK;
    bool m_failEverything = false;
    bool m_failOne = false;
    U8 m_failRegister = 0;

    // The first transactions of a test, oldest first. A timed-out read polls
    // FLAGS about a thousand times, so beyond this only the counters below
    // keep going.
    static constexpr U32 MAX_TRANSACTIONS = 64;
    Transaction m_transactions[MAX_TRANSACTIONS] = {};
    U32 m_transactionCount = 0;
    U32 m_flagsReads = 0;
    U32 m_msbReads = 0;
    U32 m_lsbReads = 0;

    // Payload of the most recent write-only transaction, copied out while the
    // component's stack buffer is still alive.
    static constexpr U32 MAX_WRITE_PAYLOAD = 8;
    U8 m_lastWrite[MAX_WRITE_PAYLOAD] = {};
    U32 m_lastWriteSize = 0;
    U32 m_writeCount = 0;
};

}  // namespace project

#endif
