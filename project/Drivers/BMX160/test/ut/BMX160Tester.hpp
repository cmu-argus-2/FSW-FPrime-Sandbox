// ======================================================================
// \title  BMX160Tester.hpp
// \brief  Unit test harness for the BMX160 component.
//
// Stands in for the I2C bus driver so the component can be exercised with no
// hardware. The fake part is a 128-byte register file that behaves like the
// real one where the component depends on it:
//
//   * burst reads return consecutive registers;
//   * writes land in the file, except CMD, which is write-only and reads
//     back as 0;
//   * reading ERR_REG clears every flag except fatal_err;
//   * it can be told to drop CMD writes, setting drop_cmd_err, as the part
//     does when a command arrives while the previous one is still running;
//   * it can be told to ignore writes to one register, to stand in for a
//     part that reads back something other than what was written;
//   * a fake BMM150 sits behind the magnetometer interface: in setup mode,
//     writing MAG_IF[3] stores MAG_IF[4] into it, and writing MAG_IF[2]
//     copies mag_rd_burst bytes of it into DATA. Transfers complete at once,
//     so STATUS reports none in progress unless a test sets mag_man_op.
//
// Every transaction is recorded so a test can assert on the exact sequence.
// ======================================================================

#ifndef PROJECT_BMX160_TESTER_HPP
#define PROJECT_BMX160_TESTER_HPP

#include "BMX160GTestBase.hpp"
#include "project/Drivers/BMX160/BMX160.hpp"

namespace project {

class BMX160Tester final : public BMX160GTestBase {
  public:
    //! BMM150 trim registers 0x5D-0x71 the fake part reports. Every term is
    //! non-zero and the signed ones mix signs, so a decoding mistake in any
    //! of them changes the result.
    static constexpr U8 TRIM_REGS[BMX160::BMM_TRIM_LENGTH] = {0xFD, 0x02, 0x00, 0x00, 0x00, 0x88, 0xFF,
                                                              0x1A, 0xFB, 0x00, 0x00, 0xFB, 0x02, 0xAB,
                                                              0x60, 0xEF, 0x99, 0x4C, 0xFF, 0xFD, 0x1D};

    static constexpr FwSizeType MAX_HISTORY_SIZE = 64;
    static constexpr FwEnumStoreType TEST_INSTANCE_ID = 0;
    static constexpr FwSizeType TEST_INSTANCE_QUEUE_DEPTH = 10;

    BMX160Tester();
    ~BMX160Tester() override;

    // ----------------------------------------------------------------------
    // Test cases
    // ----------------------------------------------------------------------

    //! Boot performs the full reset/identify/configure sequence, in order.
    void testBootSequence();

    //! A part with the wrong chip ID is never configured and stays absent.
    void testBootWrongChipId();

    //! A bus failure during boot leaves the part absent.
    void testBootBusFailure();

    //! An error_code after a data-rate write abandons boot.
    void testBootSettingRejected();

    //! A dropped power-mode command abandons boot.
    void testBootCommandDropped();

    //! A range register reading back an invalid value abandons boot.
    void testBootInvalidRangeReadback();

    //! A magnetometer interface transfer that never completes abandons boot.
    void testBootMagTransferTimeout();

    //! A part that has not booted never touches the bus.
    void testReadBeforeBoot();

    //! readGyro burst-reads the six gyroscope bytes and scales them.
    void testReadGyro();

    //! readAccel burst-reads the six accelerometer bytes and scales them.
    void testReadAccel();

    //! readMag burst-reads the eight magnetometer bytes and compensates
    //! them with the trim read from the part at boot.
    void testReadMag();

    //! A failed read is reported and publishes nothing.
    void testReadFailure();

    //! setGyroRange rewrites GYR_RANGE and rescales later reads.
    void testSetGyroRange();

    //! readErrors reads ERR_REG once per flag.
    void testReadErrors();

    //! configure() moves every transaction to the new address.
    void testConfigureAddress();

    //! The rate-group port boots once, then samples on every tick.
    void testRunBootsThenSamples();

    //! The error event throttles, and a clean read re-arms it.
    void testErrorThrottle();

  private:
    // Definitions are generated by UT_AUTO_HELPERS.
    void connectPorts();
    void initComponents();

    // ----------------------------------------------------------------------
    // Fake bus
    // ----------------------------------------------------------------------

    Drv::I2cStatus from_busWriteRead_handler(FwIndexType portNum,
                                             U32 address,
                                             Fw::Buffer& writeBuffer,
                                             Fw::Buffer& readBuffer) override;
    Drv::I2cStatus from_busWrite_handler(FwIndexType portNum, U32 address, Fw::Buffer& buffer) override;

    //! Boot the component against a healthy part and forget the traffic.
    void bootCleanly();

    //! Load three signed axis values into the data registers at `start`,
    //! little-endian, as the part would present them.
    void loadAxes(U8 start, I16 x, I16 y, I16 z);

    //! Assert that transactions `index` onward were one BMM150 write
    //! through the interface: data, address, then one STATUS poll.
    void assertBmmWrite(U32 index, U8 bmmReg, U8 value) const;

    //! Assert that transactions `index` onward were one BMM150 read of
    //! `count` bytes: burst length, address, STATUS poll, DATA read.
    void assertBmmRead(U32 index, U8 bmmReg, U32 count) const;

    //! One recorded bus transaction. For a write, `value` is the byte
    //! written; for a read, `length` is the number of bytes read.
    struct Transaction {
        U32 address;
        U8 reg;
        bool write;
        U8 value;
        U32 length;
    };

    //! Assert that transaction `index` read `length` bytes starting at `reg`.
    void assertRead(U32 index, U8 reg, U32 length = 1, U32 address = 0x68) const;

    //! Assert that transaction `index` wrote `value` to `reg`.
    void assertWrite(U32 index, U8 reg, U8 value, U32 address = 0x68) const;

    //! Make every bus transaction fail with this status.
    void failEverything(Drv::I2cStatus status);

    //! Make just this one register fail; everything else succeeds.
    void failOnly(U8 reg, Drv::I2cStatus status);

    //! Let every transaction succeed again.
    void failNothing();

    //! Forget recorded transactions and all port history.
    void resetRecording();

    BMX160 component;

    //! The fake part's register file, indexed by register address.
    static constexpr U32 REGISTER_COUNT = 128;
    U8 m_registers[REGISTER_COUNT] = {};

    //! The fake BMM150's register file, indexed by BMM150 register address.
    static constexpr U32 BMM_REGISTER_COUNT = 256;
    U8 m_bmm[BMM_REGISTER_COUNT] = {};

    //! Drop every CMD write except soft reset, setting drop_cmd_err.
    bool m_dropCommands = false;

    //! Ignore writes to one register, so it keeps whatever value a test
    //! loaded into it.
    bool m_holdOne = false;
    U8 m_heldRegister = 0;

    // Injected-failure configuration.
    Drv::I2cStatus m_forcedStatus = Drv::I2cStatus::I2C_OK;
    bool m_failEverything = false;
    bool m_failOne = false;
    U8 m_failRegister = 0;

    // Recorded transactions, oldest first.
    static constexpr U32 MAX_TRANSACTIONS = 128;
    Transaction m_transactions[MAX_TRANSACTIONS] = {};
    U32 m_transactionCount = 0;
};

}  // namespace project

#endif
