// ======================================================================
// \title  AdcsManagerTester.hpp
// \brief  Unit test harness for the AdcsManager component.
//
// Stands in for the IMU. The fake answers each magnetometer read from a
// script of samples, returns a fixed angular rate, keeps a gyroscope range
// that the component can read and write, and can be told to fail its
// boot, its magnetometer or its gyroscope. Every call is counted.
// ======================================================================

#ifndef PROJECT_ADCSMANAGER_TESTER_HPP
#define PROJECT_ADCSMANAGER_TESTER_HPP

#include "AdcsManagerGTestBase.hpp"
#include "project/Tasks/AdcsManager/AdcsManager.hpp"

namespace project {

class AdcsManagerTester final : public AdcsManagerGTestBase {
  public:
    static constexpr FwSizeType MAX_HISTORY_SIZE = 64;
    static constexpr FwEnumStoreType TEST_INSTANCE_ID = 0;
    static constexpr FwSizeType TEST_INSTANCE_QUEUE_DEPTH = 10;

    AdcsManagerTester();
    ~AdcsManagerTester() override;

    // ----------------------------------------------------------------------
    // Test cases
    // ----------------------------------------------------------------------

    //! STARTUP boots the IMU but neither senses nor controls.
    void testStartupDoesNothing();

    //! A B-dot run: snapshot, six samples, command from them, ~0.9 s.
    void testBdotCycle();

    //! NOMINAL wants 125 deg/s and leaves a range that already matches.
    void testNominalKeepsMatchingRange();

    //! A B-cross run: the gyroscope re-read every 50 ms for 1 s.
    void testBcrossCycle();

    //! LOW_POWER skips sensing and control.
    void testLowPowerSkipsSensing();

    //! Very fast tumbling turns control off without a cycle.
    void testVeryFastTumblingStopsControl();

    //! Without six good magnetometer samples, B-dot commands nothing.
    void testFailedMagnetometerStopsBdot();

    //! A failed gyroscope forces STABLE; B-dot, which needs no rate, runs.
    void testFailedGyroscopeForcesStable();

    //! A failed IMU boot is retried on the next run, and only until it works.
    void testImuBootRetried();

  private:
    // Definitions are generated by UT_AUTO_HELPERS.
    void connectPorts();
    void initComponents();

    // ----------------------------------------------------------------------
    // Fake IMU
    // ----------------------------------------------------------------------

    Fw::Success from_imuBoot_handler(FwIndexType portNum) override;
    Fw::Success from_imuReadGyro_handler(FwIndexType portNum, project::ImuVector& sample) override;
    Fw::Success from_imuReadMag_handler(FwIndexType portNum, project::ImuVector& sample) override;
    Fw::Success from_imuGetGyroRange_handler(FwIndexType portNum, project::GyroRange& range) override;
    Fw::Success from_imuSetGyroRange_handler(FwIndexType portNum, const project::GyroRange& range) override;

    //! Send one tick and run it to completion. Returns how long it took, in
    //! microseconds.
    U32 runOnce();

    //! Send a command and process it.
    void setState(project::SatelliteState::T state);
    void setController(project::AdcsController::T controller);

    //! The field the component should see for magnetometer read `index`, in T.
    AdcsLogic::Vec3 scriptedFieldT(U32 index) const;

    AdcsManager component;

    // Magnetometer script, in uT: read k returns sample min(k, last).
    static constexpr U32 MAG_SCRIPT_LENGTH = 8;
    project::ImuVector m_magScript[MAG_SCRIPT_LENGTH];

    project::ImuVector m_gyroValue;
    project::GyroRange m_range;

    Fw::Success m_bootResult = Fw::Success::SUCCESS;
    bool m_magFails = false;
    bool m_gyroFails = false;

    U32 m_bootCalls = 0;
    U32 m_gyroReads = 0;
    U32 m_magReads = 0;
    U32 m_rangeGets = 0;
    U32 m_rangeSets = 0;
    project::GyroRange m_lastRangeSet;
};

}  // namespace project

#endif
