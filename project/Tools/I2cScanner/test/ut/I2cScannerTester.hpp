// ======================================================================
// \title  I2cScannerTester.hpp
// \brief  Unit test harness for the I2cScanner component.
//
// Stands in for both I2C bus drivers. Each fake bus acknowledges only the
// addresses a test marks present, and records every probe so tests can check
// that each address is probed once, in order, with a 1-byte read.
// ======================================================================

#ifndef PROJECT_I2CSCANNER_TESTER_HPP
#define PROJECT_I2CSCANNER_TESTER_HPP

#include "I2cScannerGTestBase.hpp"
#include "project/Tools/I2cScanner/I2cScanner.hpp"

namespace project {

class I2cScannerTester final : public I2cScannerGTestBase {
  public:
    static constexpr FwSizeType MAX_HISTORY_SIZE = 16;
    static constexpr FwEnumStoreType TEST_INSTANCE_ID = 0;
    static constexpr FwSizeType TEST_INSTANCE_QUEUE_DEPTH = 10;

    I2cScannerTester();
    ~I2cScannerTester() override;

    // ----------------------------------------------------------------------
    // Test cases
    // ----------------------------------------------------------------------

    //! Each bus reports exactly the addresses that acknowledged.
    void testReportsPresentDevices();

    //! Every non-reserved address is probed once, in order, with a 1-byte read.
    void testProbesEveryAddressOnce();

    //! A bus with nothing on it reports "none".
    void testReportsEmptyBus();

    //! A bus where every address acknowledges, as when SDA is held low, keeps
    //! an exact count and cuts the list short with "...".
    void testReportsStuckBus();

  private:
    // Definitions are generated by UT_AUTO_HELPERS.
    void connectPorts();
    void initComponents();

    // ----------------------------------------------------------------------
    // Fake buses
    // ----------------------------------------------------------------------

    Drv::I2cStatus from_bus0Read_handler(FwIndexType portNum, U32 address, Fw::Buffer& buffer) override;
    Drv::I2cStatus from_bus1Read_handler(FwIndexType portNum, U32 address, Fw::Buffer& buffer) override;

    //! Record a probe on `bus` and answer it from that bus's present list.
    Drv::I2cStatus answer(U8 bus, U32 address, const Fw::Buffer& buffer);

    //! Send SCAN and check it completed.
    void scan();

    I2cScanner component;

    static constexpr U32 ADDRESS_COUNT = 128;
    static constexpr U32 BUS_COUNT = 2;

    //! Which addresses acknowledge on each bus.
    bool m_present[BUS_COUNT][ADDRESS_COUNT] = {};

    //! Every probe on each bus, in order.
    U32 m_probes[BUS_COUNT][ADDRESS_COUNT] = {};
    U32 m_probeCount[BUS_COUNT] = {};

    //! Set if any probe used a buffer other than one byte.
    bool m_wrongReadSize = false;
};

}  // namespace project

#endif
